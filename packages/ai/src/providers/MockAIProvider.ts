import {
  AIProvider,
  ChallengeGenerationContext,
  EvidenceEvaluationContext,
} from './types.js';
import { GeneratedChallenge, EvidenceEvaluationResult } from '@touch-grass/shared';
import { getFallbackChallenge } from '../fallbacks/fallbackChallenges.js';

export class MockAIProvider implements AIProvider {
  name = 'Mock AI Provider (Development & Testing)';

  async generateChallenge(context: ChallengeGenerationContext): Promise<GeneratedChallenge> {
    const { request } = context;
    const fallback = getFallbackChallenge(request.experienceType, request.durationMinutes);

    return {
      ...fallback,
      difficulty: request.difficulty || fallback.difficulty,
      title: `[Mock AI] ${fallback.title}`,
      description: `${fallback.description} (Generated by Mock AI for development testing).`,
      source: 'mock',
    };
  }

  async evaluateEvidence(context: EvidenceEvaluationContext): Promise<EvidenceEvaluationResult> {
    const { challenge, evidence } = context;
    const hasPhoto = evidence.some((e) => e.type === 'photo' && !!e.imageUrl);
    const hasText = evidence.some(
      (e) => (e.type === 'text_response' || e.type === 'observation') && !!e.textResponse
    );

    const relevanceScore = hasPhoto || hasText ? 85 : 50;
    const noveltyScore = 80;
    const interestingnessScore = 82;
    const explanationScore = hasText ? 88 : 70;

    const proposedBonusRatio = 0.8; // 80% of max bonus

    return {
      valid: true,
      relevanceScore,
      noveltyScore,
      interestingnessScore,
      explanationScore,
      proposedBonusRatio,
      feedback: `[Mock AI] Excellent submission for "${challenge.title}"! The recorded observation was thoughtful and matched the outdoor mission.`,
    };
  }
}
